def seed_ingredients():
    Base.metadata.create_all(bind=engine)

    with SessionLocal() as session:
        for item in STARTER_INGREDIENTS:
            existing = session.scalar(
                select(Ingredient).where(
                    Ingredient.canonical_name == item["canonical_name"]
                )
            )
            if existing is None:
                session.add(Ingredient(**item))

        session.commit()
        total = session.query(Ingredient).count()
        print(f"Ingredient database ready. Total records: {total}")


if __name__ == "__main__":
    seed_ingredients()